    public static function installEmpty(): void
    {
        self::connect();
        if (DB::selectOne("SELECT count(*) AS n FROM information_schema.tables WHERE table_schema='public'")->n > 0) {
            throw new \RuntimeException('Tests require empty pre-provisioned disposable schema; no reset permitted');
        }
        DB::statement('CREATE TABLE public.migrations(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, migration varchar(255) NOT NULL, batch integer NOT NULL)');
        $files = glob(dirname(__DIR__, 2).'/database/migrations/*.php');
        sort($files);
        foreach ($files as $file) {
            DB::transaction(function () use ($file) {
                $migration = require $file;
                $migration->up();
                DB::table('migrations')->insert(['migration' => basename($file, '.php'), 'batch' => 1]);
            }, 1);
        }
    }

