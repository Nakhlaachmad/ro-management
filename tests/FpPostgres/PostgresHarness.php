    public static function connect(): void
    {
        if (! self::available()) {
            throw new \RuntimeException('Explicit disposable database write authorization absent');
        }
        $name = (string) getenv('FP_TEST_DATABASE');
        $user = (string) getenv('FP_TEST_USER');
        $port = filter_var(getenv('FP_TEST_PORT'), FILTER_VALIDATE_INT);
        if (! preg_match('/\Afp_f2_test_[a-z0-9_]+\z/', $name) || $user === '' || ! $port) {
            throw new \RuntimeException('Dedicated disposable test database and explicit role required');
        }
        $root = dirname(__DIR__, 2);
        $app = new \Illuminate\Foundation\Application($root);
        $config = new \Illuminate\Config\Repository(['app' => ['timezone' => 'UTC', 'key' => '', 'cipher' => 'AES-256-CBC'], 'database' => ['default' => 'fp_test', 'connections' => ['fp_test' => ['driver' => 'pgsql', 'host' => '127.0.0.1', 'port' => $port, 'database' => $name, 'username' => $user, 'password' => (string) getenv('FP_TEST_PASSWORD'), 'charset' => 'utf8', 'prefix' => '', 'search_path' => 'public', 'sslmode' => 'prefer']]], 'fp' => ['enabled' => true, 'core_schema_only' => false, 'business_timezone' => 'UTC', 'nik_lookup_key' => 'synthetic-test-only-key-0000000000000000', 'nik_lookup_key_id' => 'synthetic-test', 'storage_adapter' => 'local'], 'permission' => require $root.'/config/permission.php']);
