        $config->set('cache', ['default' => 'array', 'stores' => ['array' => ['driver' => 'array', 'serialize' => false]]]);
        $app->instance('config', $config);
        $app->instance('hash', new \Illuminate\Hashing\HashManager($app));
        $app->instance('cache', new \Illuminate\Cache\CacheManager($app));
        $app->bind('cache.store', fn () => $app->make('cache')->store());
